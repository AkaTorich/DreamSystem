// Оби: текст ответа после броска — догадка, сам бросок, ответ по фигуре, как читали йоруба.

// about — «СОН О», guess — «ДОГАДКА» (оба уже без пробелов по краям), faces — число лиц, f — фигура
export function buildReading(about, guess, faces, f) {
  let t = '';

  t += 'Оби спрашивают не о смысле сна, а о догадке. ';
  if (guess.length > 0)
    t += 'Ты кладёшь орех у порога и спрашиваешь: «' + guess + '».';
  else
    t += 'Впиши догадку — что именно ты хочешь подтвердить у ореха.';
  if (about.length > 0)
    t += ' Сон — о том, что «' + about + '».';
  t += '\n\n';

  t += 'БРОСОК. Четыре доли ореха легли: ' + faces +
    (faces === 1 ? ' лицом (эфун) и ' : ' лицами (эфун) и ') +
    (4 - faces) + (4 - faces === 1 ? ' изнанкой.' : ' изнанками.') +
    ' Это фигура ' + f.yo + ' — ' + f.says + '\n\n';

  switch (f.kind) {
    case 'yes':
      t += 'ОТВЕТ: ДА. Эджифе — самый ясный знак согласия. ';
      t += guess.length > 0
        ? 'Дух подтверждает: «' + guess + '» — верно.'
        : 'Дух подтверждает догадку.';
      t += ' Долг словами не гаси: поблагодари Эшу и день, что говорил.';
      break;
    case 'again':
      t += 'ОТВЕТ: СКОРЕЕ ДА, но неокончательно. ';
      t += f.yo === 'Aláàfíà'
        ? 'Алафия — мир и благоволение, но ответ мягок: орех просит утверждения.'
        : 'Этава клонится к «да», но одного броска мало.';
      t += ' Брось ещё раз: если выпадет Эджифе или снова доброе — подтверждено; ' +
        'если ляжет Оканран или Ойеку — знак отзывается.';
      break;
    case 'no':
      t += 'ОТВЕТ: НЕТ. Оканран закрывает дверь: догадка неверна. ';
      t += 'Не настаивай — перебери другое предположение об источнике сна ' +
        '(ориша — божество-покровитель, предки, эгбе — небесные двойники души, ' +
        'или козни аджогун) и спроси заново.';
      break;
    case 'hardno':
      t += 'ОТВЕТ: НЕТ, и резко. Ойеку — не просто отказ: он знак, что сон НЕЧИСТ. ';
      t += 'Такой сон не пересказывают вслух. Соверши очищение у порога Эшу-Элегба, ' +
        'омой лицо, и лишь потом спрашивай снова.';
      break;
  }
  t += '\n\n';

  t += 'КАК ЧИТАЛИ ЙОРУБА. Спрашивают утром, натощак, у порога или перед святыней ' +
    'Эшу-Элегба — привратника, через которого проходят и сны, и ответы. Оби даёт лишь ' +
    '«да/нет»: сам смысл сна (вода — Йемоджа или Ошун, огонь и железо — Огун или Шанго) ' +
    'подсказывает жрец и предание, а орех только подтверждает или отвергает догадку. ' +
    'Серьёзные и повторяющиеся сны Оби не доверяют — их несут к Ифа, где выпавший одун ' +
    'даёт эсе, стих, в котором сон обретает полный сюжет и предписание.';

  return t;
}
