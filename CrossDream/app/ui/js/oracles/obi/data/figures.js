// цвет имени фигуры: «да» — белый, «ещё раз» — светлый, «нет» и «нечисто» — серый
export function accentOf(kind) {
  return kind === 'yes' ? '#FFFFFF'
    : kind === 'again' ? '#E8E8E8'
    : '#888888';
}
