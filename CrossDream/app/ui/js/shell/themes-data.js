// цвета холстов) выводит themes.js. Порядок полей в строке c:
// фон · поверхность · поверхность 2 · поверхность 3 · линия · линия яркая ·
// текст · тусклый · бледный · акцент · акцент 2 · кнопка · кнопка над · кнопка рамка ·
// золото · золото значка · опасность · шапка · поле ввода
// sky: три цвета неба сверху вниз · aur: три туманности · star: звёзды ·
// node: кружок (свет, тень) · label: подпись · sub: вторая строка подписи

const K = ['bg', 'surface', 's2', 's3', 'line', 'line2', 'text', 'dim', 'faint', 'accent', 'accent2',
  'primary', 'primaryHi', 'primaryLine', 'gold', 'goldIcon', 'danger', 'header', 'input'];

function T(id, name, tone, c, sky, aur, star, node, label, sub) {
  const t = { id, name, tone, sky, aur, star, node, label, sub };
  c.split(' ').forEach((v, i) => { t[K[i]] = v; });
  return t;
}

